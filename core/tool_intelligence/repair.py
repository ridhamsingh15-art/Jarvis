"""
Repair Pipeline — orchestrates safe reconstruction of malformed payloads.
"""


from core.task import Task
from core.tool_intelligence.argument_mapper import ArgumentMapper
from core.tool_intelligence.exceptions import SchemaResolutionError
from core.tool_intelligence.models import RepairMetrics
from core.tool_intelligence.resolver import ToolResolver
from core.tool_intelligence.schema_resolver import SchemaResolver


class PayloadRepairer:
    """Safely repairs malformed LLM tool payloads."""

    def __init__(
        self,
        resolver: ToolResolver,
        schema_resolver: SchemaResolver,
        argument_mapper: ArgumentMapper,
    ) -> None:
        self._resolver = resolver
        self._schema_resolver = schema_resolver
        self._argument_mapper = argument_mapper

    def repair(self, task: Task) -> tuple[Task, RepairMetrics]:
        """Attempt to safely normalize and repair the task payload.

        Args:
            task: The raw Task generated by the Planner or Conversation engine.

        Returns:
            A tuple of (Repaired_Task, Metrics).

        Raises:
            RepairFailedError: If the payload is hopelessly malformed and cannot be safely inferred.
        """
        # We don't repair internal system tasks
        if task.tool == "system":
            return task, RepairMetrics()

        # 1. Resolve Tool & Action Name
        resolved_tool, resolved_action, name_repaired = self._resolver.resolve(
            task.tool, task.action
        )
        tool_repaired = resolved_tool != task.tool
        action_repaired = resolved_action != task.action or name_repaired

        # 2. Retrieve Schema
        try:
            schema = self._schema_resolver.get_action_schema(
                resolved_tool, resolved_action
            )
        except SchemaResolutionError:
            # If we still can't find a schema, we can't repair arguments.
            # We return what we have so the core Validator can fail it normally.
            new_task = Task(
                tool=resolved_tool,
                action=resolved_action,
                args=task.args,
                status=task.status,
            )
            return new_task, RepairMetrics(
                tool_name_repaired=tool_repaired,
                action_name_repaired=action_repaired,
            )

        # 3. Map Arguments
        mapped_args, args_repaired_count = self._argument_mapper.map_arguments(
            task.args,
            schema.required_args,
            optional_args=getattr(schema, "optional_args", []),
            tool_name=resolved_tool,
            action_name=resolved_action,
        )

        repaired_task = Task(
            tool=resolved_tool,
            action=resolved_action,
            args=mapped_args,
            status=task.status,
            retry_count=getattr(task, "retry_count", 0),
            max_retries=getattr(task, "max_retries", 3),
            failure_history=list(getattr(task, "failure_history", [])),
        )
        
        metrics = RepairMetrics(
            tool_name_repaired=tool_repaired,
            action_name_repaired=action_repaired,
            arguments_repaired=args_repaired_count,
            total_arguments=len(mapped_args),
        )

        return repaired_task, metrics
